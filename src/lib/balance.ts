// ===== Реальный остаток: сколько денег есть прямо сейчас =====
// Отдельно от месячной статистики. Месяц отвечает на вопрос «сколько я заработал
// и потратил в сентябре», а здесь — «сколько денег у меня на руках сегодня»:
// накопительный итог по ВСЕЙ истории, без привязки к выбранному месяцу.
//
// Правила счёта — три, и все три важны:
//
// 1. Считаем в копейках целыми числами и только в конце переводим в рубли.
//    Сумма сотен операций в float даёт хвосты вида 152340.24999999997; целые
//    копейки исключают это полностью.
//
// 2. Транзит берём ВАЛОВЫМИ суммами, а не зачётом. Транзит — это реальное
//    движение денег: пришло 5000 (кошелёк потолстел), передал дальше 2700
//    (похудел), осталось 2300. Зачёт нужен статистике, чтобы источник дохода
//    не раздувался на 5000, но остаток кошелька от него не зависит:
//      (приход + max(0, нетто)) − (расход + max(0, −нетто)) = приход − расход
//    То есть чистый итог при зачёте сохраняется в точности, и наше число
//    сходится с «Balance this month» до копейки.
//
// 3. Записи БУДУЩЕЙ датой в остаток не входят. «Сколько есть сейчас» — это
//    деньги по сегодняшний день включительно; запланированная на завтра трата
//    из кармана ещё не ушла. Такие записи не теряются — они показываются
//    отдельной строкой.

import type { Tx } from './data'

export interface Balance {
  /** Остаток на сегодня: весь приход минус весь расход по сегодняшний день. */
  total: number
  /** Весь приход за всю историю (по сегодняшний день). */
  income: number
  /** Весь расход за всю историю (по сегодняшний день). */
  expense: number
  /** Насколько остаток изменился в текущем календарном месяце. */
  thisMonth: number
  /** Записи, датированные позже сегодня: в total не входят (может быть <0). */
  planned: number
  /** Сколько операций учтено в остатке. */
  count: number
  /** Дата первой операции — с неё и считается остаток. */
  firstDate: string | null
}

/** Рубли → целые копейки. Округление здесь одно на всё приложение. */
function cents(n: number): number {
  return Math.round((n || 0) * 100)
}

/**
 * Остаток на дату todayStr (строка 'YYYY-MM-DD', локальная дата пользователя).
 *
 * Даты сравниваются строками: формат 'YYYY-MM-DD' с ведущими нулями
 * упорядочен лексикографически так же, как хронологически.
 */
export function computeBalance(txs: Tx[], todayStr: string): Balance {
  const month = todayStr.slice(0, 7) // 'YYYY-MM'
  let incomeC = 0
  let expenseC = 0
  let monthC = 0
  let plannedC = 0
  let count = 0
  let firstDate: string | null = null

  for (const t of txs) {
    const date = t.date
    // Битую дату молча пропускаем: она не должна ни ломать сумму, ни попадать
    // в «первую операцию».
    if (typeof date !== 'string' || date.length < 10) continue
    const c = cents(t.amount)
    if (!Number.isFinite(c) || c < 0) continue
    const signed = t.type === 'Доход' ? c : -c

    if (date > todayStr) {
      plannedC += signed
      continue
    }

    if (t.type === 'Доход') incomeC += c
    else expenseC += c
    if (date.slice(0, 7) === month) monthC += signed
    count++
    if (!firstDate || date < firstDate) firstDate = date
  }

  return {
    total: (incomeC - expenseC) / 100,
    income: incomeC / 100,
    expense: expenseC / 100,
    thisMonth: monthC / 100,
    planned: plannedC / 100,
    count,
    firstDate,
  }
}
